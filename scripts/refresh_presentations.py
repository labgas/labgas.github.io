"""Refresh _data/presentations.yml from LaBGAScore's conference_presentations/ folder.

Lab members share their posters and talks openly in the LaBGAScore repository,
one PDF per presentation, under a fixed naming convention:

    conference_presentations/<year>/<meeting>/<First_Author_Name>_<topic>_<meeting>_<year>.pdf

This script lists that folder through the GitHub API, works out the first author
of each file by matching the start of its name against the names on the Team
page, and writes the result to _data/presentations.yml. The Team page renders
it as a "Conference presentations" row of chips under each person.

    python scripts/refresh_presentations.py            # rewrite the file
    python scripts/refresh_presentations.py --check    # report drift, change nothing
                                                       # (exit 1 if anything drifted)

Matching ignores case and accents, and treats spaces and hyphens in a name as
underscores: "Daniëlle Jongen" matches a file starting "Danielle_Jongen_".
Only the first author is linked — the file name names nobody else.

It also reports what it cannot place: a file that breaks the convention, or one
whose first author is not on the Team page. Those are listed rather than guessed.

Reads LaBGAScore's default branch on GitHub, not a local clone, so a file has to
be pushed before it can appear. Runs unauthenticated; set GITHUB_TOKEN to lift
the API rate limit.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
import unicodedata
import urllib.error
import urllib.parse
import urllib.request

ORG = "labgas"
REPO = "LaBGAScore"
FOLDER = "conference_presentations"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TEAM_YML = os.path.join(ROOT, "_data", "team.yml")
OUT_YML = os.path.join(ROOT, "_data", "presentations.yml")

HEADER = """\
# GENERATED by scripts/refresh_presentations.py — do not edit by hand.
#
# Conference posters and talks shared in
# https://github.com/labgas/LaBGAScore/tree/main/conference_presentations,
# keyed by the first author's name exactly as it appears in _data/team.yml.
# Refreshed daily by .github/workflows/refresh-repo-index.yml; to add an entry,
# push the PDF to LaBGAScore following the naming convention in that folder's
# README.md.
"""


def api(path: str):
    req = urllib.request.Request(
        "https://api.github.com/" + path,
        headers={
            "Accept": "application/vnd.github+json",
            "User-Agent": "labgas.github.io-refresh-presentations",
        },
    )
    token = os.environ.get("GITHUB_TOKEN")
    if token:
        req.add_header("Authorization", "Bearer " + token)
    with urllib.request.urlopen(req, timeout=30) as resp:
        return json.load(resp)


def norm(text: str) -> str:
    """Lower case, accents dropped, every run of non-alphanumerics to one '_'."""
    text = unicodedata.normalize("NFKD", text)
    text = "".join(c for c in text if not unicodedata.combining(c))
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")


def team_names() -> list:
    """Every name in _data/team.yml, read line-based so no YAML library is needed."""
    text = open(TEAM_YML, encoding="utf-8").read()
    return re.findall(r'^\s*-\s+name:\s*"([^"]+)"\s*$', text, re.M)


def fetch_files() -> "tuple[str, list]":
    """(default branch, paths of every file under FOLDER/)."""
    branch = api("repos/%s/%s" % (ORG, REPO))["default_branch"]
    data = api("repos/%s/%s/git/trees/%s?recursive=1" % (ORG, REPO, branch))
    if data.get("truncated"):
        raise RuntimeError("the repository tree was truncated by the API; "
                           "the listing would be incomplete")
    paths = [n["path"] for n in data.get("tree", [])
             if n.get("type") == "blob" and n["path"].startswith(FOLDER + "/")]
    return branch, sorted(paths)


def parse(path: str, names: dict, branch: str) -> "tuple[dict | None, str | None]":
    """Return (entry, None) for a usable file, or (None, reason) for one that is not."""
    parts = path.split("/")
    if len(parts) != 4:
        return None, "not at <year>/<meeting>/<file>.pdf"
    _, year, meeting, filename = parts
    if not re.fullmatch(r"\d{4}", year):
        return None, "year folder %r is not a four-digit year" % year
    stem, ext = os.path.splitext(filename)
    if ext.lower() != ".pdf":
        return None, "not a PDF"

    tokens = stem.split("_")
    tail = len(meeting.split("_")) + 1
    if len(tokens) <= tail or norm("_".join(tokens[-tail:])) != norm(meeting + "_" + year):
        return None, "file name does not end in _%s_%s" % (meeting, year)
    head = tokens[:-tail]

    # Longest name wins, so a hypothetical "Anne" never shadows "Anne-Sophie".
    for i in range(len(head) - 1, 0, -1):
        person = names.get(norm("_".join(head[:i])))
        if person:
            topic = " ".join(head[i:])
            break
    else:
        if norm("_".join(head)) in names:
            return None, "no topic between the author's name and the meeting"
        return None, "first author is not on the Team page"

    url = "https://github.com/%s/%s/blob/%s/%s" % (ORG, REPO, branch, urllib.parse.quote(path))
    return {
        "person": person,
        "label": "%s · %s %s" % (topic, meeting.replace("_", " "), year),
        "year": int(year),
        "meeting": meeting.replace("_", " "),
        "topic": topic,
        "url": url,
    }, None


def q(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(entries: list, order: list) -> str:
    """YAML text, people in Team-page order, each person's newest first."""
    by_person = {}
    for e in entries:
        by_person.setdefault(e["person"], []).append(e)
    out = [HEADER, "people:" + ("" if by_person else " {}")]
    for person in order:
        if person not in by_person:
            continue
        out.append("  %s:" % q(person))
        for e in sorted(by_person[person],
                        key=lambda e: (-e["year"], e["meeting"].lower(), e["topic"].lower())):
            out.append("    - label: %s" % q(e["label"]))
            out.append("      year: %d" % e["year"])
            out.append("      meeting: %s" % q(e["meeting"]))
            out.append("      topic: %s" % q(e["topic"]))
            out.append("      url: %s" % q(e["url"]))
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="report drift without writing; exit 1 if anything drifted")
    args = ap.parse_args()

    order = team_names()
    names = {norm(n): n for n in order}

    try:
        branch, paths = fetch_files()
    except (urllib.error.URLError, RuntimeError) as exc:
        print("Could not list %s/%s: %s" % (REPO, FOLDER, exc))
        return 2

    entries, problems = [], []
    for path in paths:
        if os.path.basename(path).lower() == "readme.md":
            continue
        entry, reason = parse(path, names, branch)
        if entry:
            entries.append(entry)
        else:
            problems.append("%s — %s" % (path, reason))

    print("%d presentation(s) in %s/%s, %d linked to the Team page."
          % (len(entries) + len(problems), REPO, FOLDER, len(entries)))
    for e in entries:
        print("  %s: %s" % (e["person"], e["label"]))

    if problems:
        print("\nNeeds a human (see conference_presentations/README.md in %s):" % REPO)
        for p in problems:
            print("  · " + p)

    new = render(entries, order)
    old = open(OUT_YML, encoding="utf-8").read() if os.path.exists(OUT_YML) else ""
    if new == old:
        print("\n_data/presentations.yml is current.")
        return 0
    if args.check:
        print("\n--check: _data/presentations.yml is out of date, not written.")
        return 1
    with open(OUT_YML, "w", encoding="utf-8", newline="") as fh:
        fh.write(new)
    print("\nWrote _data/presentations.yml")
    return 0


if __name__ == "__main__":
    sys.exit(main())
