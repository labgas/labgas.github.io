"""Refresh _data/recent_publications.yml from PubMed, and flag new papers for curation.

The Publications page has two parts. The research-line sections are curated by hand
(scripts/curated_titles.yml -> enrich_publications.py). Above them, "Recent
publications" lists everything from the last 12 months automatically; this script
keeps that list current.

    python scripts/refresh_recent_publications.py                      # rewrite the file
    python scripts/refresh_recent_publications.py --check              # report drift only
    python scripts/refresh_recent_publications.py --issue-body new.md  # also write an issue
                                                                       # body for new papers

Search: Van Oudenhove L as author, Leuven in an affiliation, publication date within
the last 12 months. Each record's full entry is then checked to be Lukas — forename,
or Leuven in that author's own affiliation — because "Van Oudenhove L" also fits an
unrelated entomologist and Lore Van Oudenhove in Ghent. Errata are dropped.

New papers. The file also keeps `reported:`, every PMID already raised for curation.
A paper that is new to that list, and not already among the curated highlights, is
written to the --issue-body file with a suggested research line, so the daily
workflow can open one GitHub issue for it. The suggestion comes from the keyword
lists in LINE_KEYWORDS below: transparent and crude, and only ever a suggestion —
whether a paper becomes a highlight, and under which line, stays a human decision.

Stdlib only. Shares its PubMed and lab-author helpers with enrich_publications.py.
"""

from __future__ import annotations

import argparse
import datetime as dt
import os
import re
import sys
import time
import urllib.parse
import urllib.request
import xml.etree.ElementTree as ET

from enrich_publications import (
    DELAY, EMAIL, EUTILS, LINE_LABELS, LINE_ORDER, ROOT, TOOL,
    _get, lab_authors, load_lab_members, yq,
)

OUT = os.path.join(ROOT, "_data", "recent_publications.yml")
CURATED = os.path.join(ROOT, "_data", "publications.yml")
WINDOW_DAYS = 365
QUERY = 'Van Oudenhove L[au] AND Leuven[ad] AND ("{since}"[dp] : "3000"[dp])'
EXCLUDE_TYPES = {"Published Erratum"}

# Suggested research line: a title hit counts 2, an abstract hit 1, and the line
# with the highest score is suggested if it reaches 2. Edit freely — these only
# ever produce a suggestion in the issue.
LINE_KEYWORDS = {
    "symptoms": [
        r"irritable bowel", r"\bIBS\b", r"dyspeps", r"functional gastrointestinal",
        r"gut-brain interaction", r"\bDGBI", r"visceral", r"\bpain\b", r"fatigue",
        r"myalgic", r"\bME/CFS\b", r"interocept", r"symptom", r"heartburn", r"reflux",
        r"inflammatory bowel", r"\bIBD\b", r"fibromyalgia", r"somat",
    ],
    "appetite": [
        r"appetite", r"\bfood", r"eating", r"satiat", r"satiety", r"hunger", r"obes",
        r"bariatric", r"GLP-1", r"semaglutide", r"reward", r"sweeten", r"erythritol",
        r"sucrose", r"ghrelin", r"body weight", r"weight loss", r"binge",
    ],
    "microbiota": [
        r"microbio", r"microbial", r"short-chain fatty acid", r"\bSCFA", r"butyrate",
        r"probiotic", r"prebiotic", r"\bstress", r"cortisol", r"\baffect", r"\bmood",
        r"depress", r"emotion", r"fear",
    ],
    "methods": [
        r"multivariate", r"machine learning", r"decoding", r"signature", r"representational",
        r"\bMVPA\b", r"connectivity", r"pattern", r"predictive model", r"\bPET\b",
        r"spectroscopy", r"\bMRS\b",
    ],
}

HEADER = """\
# GENERATED by scripts/refresh_recent_publications.py — do not edit by hand.
#
# Every PubMed record from the last 12 months with Van Oudenhove L as author and
# Leuven in an affiliation, newest first. Shown as "Recent publications" at the top
# of the Publications page. Refreshed daily by .github/workflows/refresh-repo-index.yml.
#
# `reported` lists every PMID already raised in a GitHub issue for curation, so no
# paper is raised twice. Deleting a PMID from it raises that paper again.
"""


def esearch_all(term: str) -> "list[str]":
    url = (f"{EUTILS}/esearch.fcgi?db=pubmed&retmode=json&retmax=500"
           f"&tool={TOOL}&email={EMAIL}&term={urllib.parse.quote(term)}")
    return _get(url).get("esearchresult", {}).get("idlist", [])


def esummary(pmids: "list[str]") -> dict:
    if not pmids:
        return {}
    url = (f"{EUTILS}/esummary.fcgi?db=pubmed&retmode=json"
           f"&tool={TOOL}&email={EMAIL}&id={','.join(pmids)}")
    return _get(url).get("result", {})


def details(pmids: "list[str]") -> dict:
    """PMID -> (abstract text, whether the Van Oudenhove author is Lukas).

    The summary record only carries "Van Oudenhove L", which also fits Lore Van
    Oudenhove (a Ghent biotech researcher) — and Leuven[ad] does not exclude her,
    since it matches any author's affiliation. The full record has the forename
    and per-author affiliations, so decide here: forename "Luk…", or an initial
    only with Leuven in that author's own affiliation.
    """
    if not pmids:
        return {}
    url = (f"{EUTILS}/efetch.fcgi?db=pubmed&retmode=xml"
           f"&tool={TOOL}&email={EMAIL}&id={','.join(pmids)}")
    req = urllib.request.Request(url, headers={"User-Agent": f"{TOOL} ({EMAIL})"})
    with urllib.request.urlopen(req, timeout=60) as fh:
        root = ET.fromstring(fh.read())
    out = {}
    for art in root.iter("PubmedArticle"):
        pmid = art.findtext(".//PMID", default="")
        abstract = " ".join("".join(t.itertext()) for t in art.iter("AbstractText"))
        is_lukas = False
        for a in art.iter("Author"):
            if "oudenhove" not in (a.findtext("LastName") or "").lower():
                continue
            fore = (a.findtext("ForeName") or "").strip()
            affil = " ".join(x.text or "" for x in a.iter("Affiliation"))
            if fore.lower().startswith("luk") or (len(fore.rstrip(".")) <= 1 and "leuven" in affil.lower()):
                is_lukas = True
        out[pmid] = (abstract, is_lukas)
    return out


def record(pmid: str, d: dict, members) -> dict:
    authors = [a.get("name", "") for a in d.get("authors", []) if a.get("authtype") == "Author"]
    doi = next((a.get("value", "") for a in d.get("articleids", []) if a.get("idtype") == "doi"), "")
    return {
        "title": (d.get("title") or "").rstrip("."),
        "authors": authors,
        "lab_authors": lab_authors(authors, members),
        "journal": d.get("fulljournalname") or d.get("source", ""),
        "year": (d.get("pubdate", "") or "").split(" ")[0],
        "volume": d.get("volume", ""),
        "issue": d.get("issue", ""),
        "pages": d.get("pages", ""),
        "pmid": pmid,
        "doi": doi,
        # Sort key only; not written out.
        "sort": d.get("sortpubdate", ""),
        "types": set(d.get("pubtype", [])),
    }


def suggest(title: str, abstract: str) -> "tuple[str | None, list[str]]":
    scores, hits = {}, {}
    for line, patterns in LINE_KEYWORDS.items():
        for p in patterns:
            t = len(re.findall(p, title, re.I))
            a = len(re.findall(p, abstract, re.I))
            if t or a:
                scores[line] = scores.get(line, 0) + 2 * t + a
                hits.setdefault(line, []).append(re.sub(r"\\b|\\", "", p))
    if not scores:
        return None, []
    best = max(LINE_ORDER, key=lambda k: scores.get(k, 0))
    if scores.get(best, 0) < 2:
        return None, []
    return best, hits[best]


def curated_pmids() -> "dict[str, str]":
    """PMID -> research line, for the papers already among the curated highlights."""
    if not os.path.exists(CURATED):
        return {}
    out, line = {}, None
    for raw in open(CURATED, encoding="utf-8"):
        m = re.match(r"^\s*- line:\s*(\w+)", raw)
        if m:
            line = m.group(1)
        m = re.match(r'^\s*pmid:\s*"?(\d+)"?', raw)
        if m and line:
            out[m.group(1)] = line
    return out


def read_reported() -> "list[str]":
    if not os.path.exists(OUT):
        return []
    text = open(OUT, encoding="utf-8").read()
    block = re.search(r"^reported:\s*\n((?:\s+- .*\n?)*)", text, re.M)
    return re.findall(r'"(\d+)"', block.group(1)) if block else []


def render(items: "list[dict]", reported: "list[str]") -> str:
    out = [HEADER, "items:" + ("" if items else " []")]
    for r in items:
        out.append(f"  - title: {yq(r['title'])}")
        for key in ("journal", "year", "volume", "issue", "pages", "pmid", "doi"):
            out.append(f"    {key}: {yq(r[key])}")
        out.append("    authors:")
        out.extend(f"      - {yq(a)}" for a in r["authors"])
        if r["lab_authors"]:
            out.append("    lab_authors:")
            out.extend(f"      - {yq(a)}" for a in r["lab_authors"])
    out.append("")
    out.append("reported:" + ("" if reported else " []"))
    out.extend(f"  - {yq(p)}" for p in sorted(reported, key=int))
    return "\n".join(out) + "\n"


def issue_body(new: "list[dict]", abstracts_by_pmid: dict) -> str:
    lines = [
        f"PubMed has {len(new)} new paper(s) with Lukas Van Oudenhove as author and a Leuven "
        "affiliation. They already appear under **Recent publications** on the "
        "[Publications page](https://labgas.github.io/publications/) automatically.",
        "",
        "**To also make one a highlight under a research line:** open "
        "[`scripts/curated_titles.yml`](https://github.com/labgas/labgas.github.io/edit/main/scripts/curated_titles.yml), "
        "paste its title line under the right research line, and commit. The page updates by itself "
        "within a few minutes. The suggested line below comes from keyword rules — check it.",
        "",
        "Close this issue when you are done; nothing else needs doing for papers you skip.",
        "",
    ]
    for r in new:
        line, words = suggest(r["title"], abstracts_by_pmid.get(r["pmid"], ""))
        lab = ", ".join(r["lab_authors"]) or "—"
        lines += [
            f"### {r['title']}",
            f"*{r['journal']}* {r['year']} · [PubMed {r['pmid']}](https://pubmed.ncbi.nlm.nih.gov/{r['pmid']}/)"
            + (f" · [doi:{r['doi']}](https://doi.org/{r['doi']})" if r["doi"] else ""),
            f"Lab authors: {lab}",
            "",
            (f"Suggested line: **{line}** — {LINE_LABELS[line]} (matched: {', '.join(words)})"
             if line else "Suggested line: **no clear fit** — choose one, or skip this paper"),
            "",
            "```yaml",
            f"  - {yq(r['title'])}",
            "```",
            "",
        ]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="report drift without writing; exit 1 if anything drifted")
    ap.add_argument("--issue-body", metavar="PATH",
                    help="write a GitHub issue body here if there are new papers to report")
    args = ap.parse_args()

    since = (dt.date.today() - dt.timedelta(days=WINDOW_DAYS)).strftime("%Y/%m/%d")
    members = load_lab_members()
    try:
        pmids = esearch_all(QUERY.format(since=since))
        time.sleep(DELAY)
        summaries = esummary(pmids)
    except Exception as exc:
        print(f"Could not query PubMed: {type(exc).__name__}: {exc}")
        return 2

    try:
        time.sleep(DELAY)
        full = details(pmids)
    except Exception as exc:
        print(f"Could not fetch full PubMed records: {type(exc).__name__}: {exc}")
        return 2

    items, dropped = [], []
    for pmid in pmids:
        r = record(pmid, summaries.get(pmid, {}), members)
        if not any("oudenhove" in a.lower() for a in r["authors"]):
            dropped.append(f"PMID {pmid}: no Van Oudenhove in the author list")
        elif not full.get(pmid, ("", False))[1]:
            dropped.append(f"PMID {pmid}: the Van Oudenhove author is not Lukas")
        elif r["types"] & EXCLUDE_TYPES:
            dropped.append(f"PMID {pmid}: {', '.join(sorted(r['types'] & EXCLUDE_TYPES))}")
        else:
            items.append(r)
    items.sort(key=lambda r: (r["sort"], r["pmid"]), reverse=True)

    reported = read_reported()
    curated = curated_pmids()
    new = [r for r in items if r["pmid"] not in reported and r["pmid"] not in curated]

    print(f"{len(items)} publication(s) since {since}"
          + (f"; {len(dropped)} left out" if dropped else "") + ".")
    for r in items:
        mark = " (new)" if r in new else (f" (highlight: {curated[r['pmid']]})" if r["pmid"] in curated else "")
        print(f"  {r['year']}  {r['title'][:80]}{mark}")
    for d in dropped:
        print(f"  · left out: {d}")

    if new and args.issue_body and not args.check:
        with open(args.issue_body, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(issue_body(new, {p: v[0] for p, v in full.items()}))
        reported = reported + [r["pmid"] for r in new]
        print(f"\n{len(new)} new paper(s) written to {args.issue_body}")
    elif new:
        print(f"\n{len(new)} new paper(s) not yet reported (pass --issue-body to report them)")

    new_text = render(items, reported)
    old_text = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if new_text == old_text:
        print("\n_data/recent_publications.yml is current.")
        return 0
    if args.check:
        print("\n--check: _data/recent_publications.yml is out of date, not written.")
        return 1
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(new_text)
    print("\nWrote _data/recent_publications.yml")
    return 0


if __name__ == "__main__":
    sys.exit(main())
